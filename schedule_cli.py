#!/usr/bin/env python3
"""schedule_cli.py — ядро сервиса автоматического составления расписания.

I. НАЗНАЧЕНИЕ
    Строит несколько лучших вариантов семестрового расписания колледжа по
    справочникам, учебной нагрузке и пожеланиям преподавателей. Это ядро без
    веб-интерфейса (этапы 1–3 плана работ): доменная модель, генератор
    синтетических данных, быстрые проверки, решатель CP-SAT, назначение
    аудиторий и независимый валидатор. Веб-сервис (Django + React) будет
    вызывать те же функции.

II. ВХОД
    JSON-файл задачи (формат scheduler/serialization.py, schema_version = 1):
    сетка пар, курсы, группы, подгруппы, преподаватели с сеткой −2…+2,
    дисциплины, аудитории, элементы нагрузки, синхронные блоки, допустимые
    объединения, закрепления. Синтетическую задачу создаёт команда `generate`.

III. ВЫХОД
    JSON-файл(ы) расписания: назначения «элемент → неделя (обе/нечёт./чёт.) →
    слот → аудитория или онлайн» + meta (параметры запуска, seed, разбивка
    штрафа). Коды выхода: 0 — успех; 1 — ошибка ввода/окружения;
    2 — расписание не построено (противоречие или нет времени);
    3 — валидатор нашёл жёсткие нарушения.

IV. АЛГОРИТМ
    1. precheck: мгновенные проверки («у Петрова 8 пар и 6 слотов»).
    2. CP-SAT, этап 1: булевы переменные «единица × слот (× неделя)»,
       жёсткие ограничения, агрегированные аудитории по порогам вместимости;
       фаза 0 — любое допустимое решение, затем оптимизация с подсказкой;
       взвешенная сумма или лексикографическая цепочка мягких критериев.
    3. Этап 2: аудитории — задача о назначениях по слотам со стабильностью.
    4. Варианты: «отличаться минимум на K назначений» и решить снова.
    5. Валидатор пересчитывает всё заново и выдаёт разбивку штрафа.
    6. Неразрешимость: минимальный набор противоречий через assumptions.
    Подробно — docs/ARCHITECTURE.md.

V. ОГРАНИЧЕНИЯ И ДОПУЩЕНИЯ
    * Значения с пометкой [уточнить] — заглушки в scheduler/defaults.py,
      список открытых вопросов — docs/OPEN_QUESTIONS.md.
    * Объединение групп — «всё или ничего» для набора.
    * У всех занятий синхронного блока одинаковое число пар за цикл.
    * Тип аудитории требуется точно (без подстановки «лекционная вместо обычной»).
    * Время переходов между корпусами не учитывается (по ТЗ).

VI. ЗАВИСИМОСТИ
    Python 3.12+ (рекомендуется 3.13), ortools==9.15.6755. Проверка окружения:
    `python verify_install.py`.

VII. ПРИМЕРЫ
    python schedule_cli.py generate -o data/problem.json --planted data/planted.json
    python schedule_cli.py precheck data/problem.json
    python schedule_cli.py solve data/problem.json -o output/schedule.json --time 120 --variants 3
    python schedule_cli.py validate data/problem.json output/schedule_v1.json --issues
    python schedule_cli.py show data/problem.json output/schedule_v1.json ИС-11 --week even
    python schedule_cli.py bench --seeds 3 --time 60 -o output/bench.json
"""

